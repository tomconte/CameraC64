@Test(arguments: [0, 1, 2, 3, 300, 5000])
func deflateRoundTrips(length: Int) throws {
    var generator = SeededGenerator(seed: UInt64(length))
    // Runs of random lengths, as in a picture, and noise.
    var bytes: [UInt8] = []
    while bytes.count < length {
        let byte = UInt8.random(in: 0...255, using: &generator)
        bytes += Array(repeating: byte, count: Int.random(in: 1...300, using: &generator))
    }
    bytes = Array(bytes.prefix(length))
    #expect(try Deflate.inflate(Deflate.deflate(bytes)) == bytes)
}

